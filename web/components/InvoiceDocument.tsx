"use client";

import { useEffect } from "react";
import type { Invoice } from "@/lib/contract";
import { config, explorer } from "@/lib/config";
import { invoicePrintTitle } from "@/lib/invoice-helpers";
import {
  formatAmount,
  formatDate,
  humanizeDescription,
  shortAddress,
} from "@/lib/format";
import { useTokenMeta } from "@/lib/use-token-meta";
import { StatusBadge } from "./ui";
import { LogoMark } from "./LogoMark";
import { Modal } from "./Modal";

// A clean, self-contained invoice sheet. Used for (a) the pre-send preview on
// the create page and (b) PDF export via the browser's print-to-PDF — the
// global @media print rules in globals.css show only the .print-area. No PDF
// library needed; the print dialog's "Save as PDF" produces a shareable file.

export function InvoiceDocument({
  invoice,
  txHash,
}: {
  invoice: Invoice;
  txHash?: string;
}) {
  const token = useTokenMeta(invoice.token);
  const isPaid = invoice.status === "Paid";
  return (
    <div className="card invoice-print space-y-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className="flex items-center gap-2">
          <span className="grid h-9 w-9 place-items-center rounded-lg bg-brand-500 text-white">
            <LogoMark className="h-6 w-6" />
          </span>
          <div>
            <p className="font-bold tracking-tight">PayLoop</p>
            <p className="text-xs text-slate-400">
              {isPaid ? "Receipt" : "Invoice"} #{invoice.id}
            </p>
          </div>
        </div>
        <StatusBadge status={invoice.status} />
      </div>

      {isPaid && (
        <div>
          <p className="text-xl font-bold tracking-tight">Receipt</p>
          <p className="text-sm text-slate-400">
            Paid in full on {formatDate(invoice.paidAt)}
          </p>
        </div>
      )}

      <div className="text-3xl font-bold tracking-tight">
        {formatAmount(invoice.amount, token.decimals)}{" "}
        <span className="text-lg text-slate-400">{token.symbol}</span>
      </div>

      <div className="space-y-2 rounded-lg bg-ink-900/60 p-4 text-sm">
        <div className="flex items-start justify-between gap-4">
          <div className="flex-1">
            <p className="text-xs uppercase tracking-wide text-slate-500">
              Billed to (client)
            </p>
            <p className="mt-0.5 font-mono text-xs">{invoice.client}</p>
          </div>
          <div className="flex-1 text-right">
            <p className="text-xs uppercase tracking-wide text-slate-500">
              From (freelancer)
            </p>
            <p className="mt-0.5 font-mono text-xs">{invoice.freelancer}</p>
          </div>
        </div>
        <div className="flex flex-wrap justify-between gap-x-6 gap-y-1 pt-2">
          <span className="text-slate-500">
            Created{" "}
            <span className="font-medium text-slate-300">
              {formatDate(invoice.createdAt)}
            </span>
          </span>
          {invoice.dueDate > 0n && (
            <span className="text-slate-500">
              Due{" "}
              <span className="font-medium text-slate-300">
                {formatDate(invoice.dueDate)}
              </span>
            </span>
          )}
          {isPaid && (
            <span className="text-slate-500">
              Paid{" "}
              <span className="font-medium text-slate-300">
                {formatDate(invoice.paidAt)}
              </span>
            </span>
          )}
        </div>
      </div>

      <div className="border-t border-white/10 pt-4">
        <p className="text-xs uppercase tracking-wide text-slate-500">
          For services rendered
        </p>
        <p className="mt-1 text-slate-200">
          {humanizeDescription(invoice.description) || "—"}
        </p>
      </div>

      <div className="border-t border-white/10 pt-4 text-xs text-slate-500">
        <p className="font-semibold text-slate-300">
          {formatAmount(invoice.amount, token.decimals)} {token.symbol}{" "}
          {invoice.status === "Paid" ? "paid" : "due"} — settled on-chain in
          seconds on Stellar.
        </p>
        <p className="mt-1">
          Generated by PayLoop
          {config.network !== "PUBLIC" && " · Stellar testnet demo"} ·{" "}
          {shortAddress(invoice.freelancer)}
        </p>
        {isPaid && (
          <div className="mt-3 space-y-1 border-t border-white/10 pt-3">
            <p className="font-semibold text-slate-300">Verify on-chain</p>
            <p>
              Invoice <span className="font-mono">#{invoice.id}</span>
            </p>
            <p className="break-all">
              Contract{" "}
              <a
                href={explorer.contract(config.contractId)}
                target="_blank"
                rel="noopener noreferrer"
                className="font-mono text-brand-300 underline-offset-2 hover:underline"
              >
                {config.contractId}
              </a>
            </p>
            {txHash && (
              <p className="break-all">
                Transaction{" "}
                <a
                  href={explorer.tx(txHash)}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="font-mono text-brand-300 underline-offset-2 hover:underline"
                >
                  {txHash}
                </a>
              </p>
            )}
          </div>
        )}
      </div>
    </div>
  );
}

// Modal that previews an invoice and offers Edit / Save-as-PDF. The printable
// sheet sits inside a .print-area so the @media print rules isolate it.
export function InvoicePreview({
  invoice,
  open,
  onClose,
  onConfirm,
  confirming,
  confirmLabel = "Create invoice",
  txHash,
}: {
  invoice: Invoice | null;
  open: boolean;
  onClose: () => void;
  onConfirm?: () => void;
  confirming?: boolean;
  confirmLabel?: string;
  /** Settlement transaction hash for a paid invoice, when known. */
  txHash?: string;
}) {
  // Issue #67: "Save as PDF" proposes the page title as the filename, so while
  // the preview is open the title is PayLoop-Invoice-<id> (PayLoop-Receipt-<id>
  // once paid). The previous title is restored on close/unmount.
  const printTitle = invoice ? invoicePrintTitle(invoice) : null;
  useEffect(() => {
    if (!open || !printTitle) return;
    const previous = document.title;
    document.title = printTitle;
    return () => {
      document.title = previous;
    };
  }, [open, printTitle]);

  // Escape and focus handling are owned by Modal, so no duplicate listener here.
  if (!open || !invoice) return null;

  return (
    <Modal
      open={open}
      onClose={onClose}
      label="Invoice preview"
      panelClassName="max-h-[90vh] w-full max-w-lg space-y-4 overflow-y-auto"
    >
      <div className="print-area">
        <InvoiceDocument invoice={invoice} txHash={txHash} />
      </div>

      <div className="flex flex-wrap justify-end gap-2 print:hidden">
        <button onClick={onClose} className="btn-ghost text-sm">
          Edit
        </button>
        <button onClick={() => window.print()} className="btn-ghost text-sm">
          ⬇ Save as PDF
        </button>
        {onConfirm && (
          <button
            onClick={onConfirm}
            disabled={confirming}
            className="btn-primary text-sm"
          >
            {confirming ? "Creating…" : confirmLabel}
          </button>
        )}
      </div>
    </Modal>
  );
}
