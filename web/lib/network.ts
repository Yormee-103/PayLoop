import { config } from "./config";

/**
 * Returns the network demo label for UI footers.
 * Empty string on mainnet (PUBLIC); "Testnet demo" on testnet/custom.
 */
export function getNetworkDemoLabel(network: string = config.network): string {
  return network === "PUBLIC" ? "" : "Testnet demo";
}

/**
 * Generates the invoice sheet footer label.
 * Omits "Stellar testnet demo" when running on mainnet (PUBLIC).
 */
export function getInvoiceFooterLabel(
  freelancerSnippet: string,
  network: string = config.network
): string {
  const demoPart = network === "PUBLIC" ? "" : " · Stellar testnet demo";
  return `Generated by PayLoop${demoPart} · ${freelancerSnippet}`;
}
